<?php

namespace App\Services;

use App\Models\MaintenanceRequest;
use App\Models\PmPlan;
use App\Models\PmSchedule;
use App\Models\WorkOrder;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * Work order life cycle:
 *   open -> assigned -> in_progress -> (on_hold) -> completed -> verification_pending -> closed
 */
class WorkOrderService
{
    /** Step 5 of the approval flow. Called by ApprovalWorkflowService. */
    public function createFromRequest(MaintenanceRequest $request, string $source = 'request'): WorkOrder
    {
        $assessment = $request->latestAssessment;

        $workOrder = WorkOrder::create([
            'wo_no'           => DocumentNumberService::next('work_order'),
            'request_id'      => $request->id,
            'asset_id'        => $request->asset_id,
            'department_id'   => $request->department_id,
            'source'          => $source,
            'work_type'       => $request->request_type,
            'priority'        => $request->priority,
            'planned_start'   => now()->toDateString(),
            'planned_end'     => now()->addDays($this->plannedDays($request->priority))->toDateString(),
            'description'     => $request->problem_description,
            'estimated_cost'  => $request->approved_cost ?? $request->estimated_cost ?? 0,
            'permit_required' => $assessment?->permit_required ?? false,
            'vendor_id'       => $assessment?->external_vendor_required ? $assessment->vendor_id : null,
            'status'          => 'open',
            'created_by'      => auth()->id(),
        ]);

        $request->update(['status' => 'work_order_created']);
        $request->logHistory('work_order_created', 'Work order ' . $workOrder->wo_no . ' generated', 'approved', 'work_order_created');
        $workOrder->logHistory('created', 'Generated from request ' . $request->request_no . ($source === 'emergency' ? ' (EMERGENCY)' : ''), null, 'open');

        $this->updateAssetStatus($workOrder, 'under_maintenance');

        NotificationService::notifyPermission('pm.workorders.assign', 'work_order_new',
            'Work order ' . $workOrder->wo_no . ' needs assignment', $workOrder->asset->name, route('work-orders.show', $workOrder));

        return $workOrder;
    }

    /** Work order generated by the PM scheduler. */
    public function createFromSchedule(PmSchedule $schedule): WorkOrder
    {
        $plan = $schedule->plan;

        $workOrder = WorkOrder::create([
            'wo_no'          => DocumentNumberService::next('work_order'),
            'asset_id'       => $plan->component_id ?: $plan->asset_id,
            'department_id'  => $plan->asset->department_id,
            'source'         => 'preventive',
            'work_type'      => 'preventive',
            'priority'       => 'medium',
            'team_id'        => $plan->team_id,
            'assigned_to'    => $plan->assigned_to,
            'planned_start'  => ($schedule->due_date ?? now())->toDateString(),
            'planned_end'    => ($schedule->due_date ?? now())->copy()->addDays(3)->toDateString(),
            'description'    => 'Preventive maintenance: ' . $plan->name . ' (' . $plan->plan_no . ')',
            'estimated_cost' => $plan->estimated_cost,
            'status'         => $plan->assigned_to ? 'assigned' : 'open',
            'created_by'     => null,
        ]);

        $workOrder->logHistory('created', 'Generated by PM schedule (' . $schedule->trigger_reason . ')', null, $workOrder->status);

        if ($plan->assigned_to) {
            NotificationService::notifyUser($plan->assigned_to, 'work_order_assigned',
                'PM work order ' . $workOrder->wo_no . ' assigned to you', $plan->name, route('work-orders.show', $workOrder));
        } else {
            NotificationService::notifyPermission('pm.workorders.assign', 'work_order_new',
                'PM work order ' . $workOrder->wo_no . ' needs assignment', $plan->name, route('work-orders.show', $workOrder));
        }

        return $workOrder;
    }

    /** Manual work order (no request), e.g. small jobs. Requires pm.workorders.create. */
    public function createManual(array $data): WorkOrder
    {
        return DB::transaction(function () use ($data) {
            $workOrder = WorkOrder::create(array_merge($data, [
                'wo_no'      => DocumentNumberService::next('work_order'),
                'source'     => 'manual',
                'status'     => !empty($data['assigned_to']) ? 'assigned' : 'open',
                'created_by' => auth()->id(),
            ]));
            $workOrder->logHistory('created', 'Manual work order created', null, $workOrder->status);
            if ($workOrder->assigned_to) {
                NotificationService::notifyUser($workOrder->assigned_to, 'work_order_assigned',
                    'Work order ' . $workOrder->wo_no . ' assigned to you', $workOrder->asset->name, route('work-orders.show', $workOrder));
            }
            return $workOrder;
        });
    }

    public function assign(WorkOrder $workOrder, array $data): void
    {
        $this->assertStatus($workOrder, ['open', 'assigned', 'on_hold']);

        DB::transaction(function () use ($workOrder, $data) {
            $from = $workOrder->status;
            $workOrder->update(array_merge($data, ['status' => $from === 'on_hold' ? 'on_hold' : 'assigned']));
            $workOrder->logHistory('assigned', 'Assigned to ' . ($workOrder->technician?->name ?? 'team'), $from, $workOrder->status);

            NotificationService::notifyUser($workOrder->assigned_to, 'work_order_assigned',
                'Work order ' . $workOrder->wo_no . ' assigned to you', $workOrder->asset->name, route('work-orders.show', $workOrder));
        });
    }

    public function start(WorkOrder $workOrder): void
    {
        $this->assertStatus($workOrder, ['assigned', 'on_hold', 'open']);

        // Safety rule: permit-required jobs cannot start without an ACTIVE permit
        if ($workOrder->permit_required && $workOrder->permits()->where('status', 'active')->doesntExist()) {
            throw ValidationException::withMessages(['permit' => 'A Permit to Work must be approved and active before this job can start.']);
        }

        DB::transaction(function () use ($workOrder) {
            $from = $workOrder->status;
            $workOrder->update([
                'status'       => 'in_progress',
                'actual_start' => $workOrder->actual_start ?? now(),
                'assigned_to'  => $workOrder->assigned_to ?? auth()->id(),
            ]);
            $workOrder->logHistory('started', 'Work started', $from, 'in_progress');
            if ($workOrder->request) {
                $workOrder->request->update(['status' => 'in_progress']);
            }
        });
    }

    public function hold(WorkOrder $workOrder, string $reason): void
    {
        $this->assertStatus($workOrder, ['in_progress', 'assigned']);
        $from = $workOrder->status;
        $workOrder->update(['status' => 'on_hold', 'hold_reason' => $reason]);
        $workOrder->logHistory('on_hold', $reason, $from, 'on_hold');
    }

    /** Technician records execution details and marks the job complete. */
    public function complete(WorkOrder $workOrder, array $data, ?array $before = null, ?array $after = null): void
    {
        $this->assertStatus($workOrder, ['in_progress', 'on_hold']);

        DB::transaction(function () use ($workOrder, $data, $before, $after) {
            $from = $workOrder->status;
            $actualEnd = $data['actual_end'] ?? now();
            $otherCost = (float) ($data['other_cost'] ?? 0); // vendor / misc cost typed by technician
            unset($data['other_cost']);

            $workOrder->update(array_merge($data, [
                'status'      => 'verification_pending',
                'actual_end'  => $actualEnd,
                'labour_hours'=> $workOrder->labour()->sum('hours') ?: ($data['labour_hours'] ?? 0),
            ]));
            $workOrder->refresh();
            $workOrder->update(['actual_cost' => $this->calculateActualCost($workOrder, $otherCost)]);

            AttachmentService::storeMany($workOrder, $before, 'before_photo');
            AttachmentService::storeMany($workOrder, $after, 'after_photo');

            $workOrder->logHistory('completed', 'Work completed, awaiting verification', $from, 'verification_pending');
            if ($workOrder->request) {
                $workOrder->request->update(['status' => 'verification_pending']);
            }

            NotificationService::notifyPermission('pm.workorders.verify', 'work_order_verify',
                'Work order ' . $workOrder->wo_no . ' needs verification', $workOrder->asset->name, route('work-orders.show', $workOrder), 'warning');
        });
    }

    /** Supervisor verification. Either closes the WO or sends it back to the technician. */
    public function verify(WorkOrder $workOrder, array $data): void
    {
        $this->assertStatus($workOrder, ['verification_pending', 'completed']);

        DB::transaction(function () use ($workOrder, $data) {
            // Only the verification fields go into the verification record
            $verificationFields = ['machine_operation_ok', 'safety_ok', 'repair_quality_ok', 'production_ready', 'test_results', 'observations', 'decision', 'remarks'];
            $verification = $workOrder->verifications()->create(array_merge(
                array_intersect_key($data, array_flip($verificationFields)),
                ['verified_by' => auth()->id(), 'verification_date' => now()]
            ));

            $from = $workOrder->status;

            if ($data['decision'] === 'sent_back') {
                $workOrder->update(['status' => 'in_progress']);
                $workOrder->logHistory('verification_sent_back', $data['remarks'] ?? 'Sent back for additional work', $from, 'in_progress');
                NotificationService::notifyUser($workOrder->assigned_to, 'work_order_sent_back',
                    'Work order ' . $workOrder->wo_no . ' sent back', $data['remarks'] ?? '', route('work-orders.show', $workOrder), 'warning');
                return;
            }

            // Approved -> close
            $downtime = $workOrder->downtime_hours;
            if (!$downtime && $workOrder->actual_start && $workOrder->actual_end) {
                $downtime = round($workOrder->actual_start->diffInMinutes($workOrder->actual_end) / 60, 2);
            }

            $workOrder->update([
                'status'               => 'closed',
                'verified_by'          => auth()->id(),
                'verified_at'          => now(),
                'closed_by'            => auth()->id(),
                'closed_at'            => now(),
                'final_machine_status' => $data['final_machine_status'] ?? 'active',
                'final_remarks'        => $data['remarks'] ?? null,
                'downtime_hours'       => $downtime,
                'actual_cost'          => $data['actual_cost'] ?? $workOrder->actual_cost,
            ]);
            $workOrder->logHistory('closed', 'Verified and closed. ' . ($data['remarks'] ?? ''), $from, 'closed');

            $this->updateAssetStatus($workOrder, $workOrder->final_machine_status);

            if ($workOrder->request) {
                $workOrder->request->update([
                    'status'          => 'closed',
                    'closed_at'       => now(),
                    'closed_by'       => auth()->id(),
                    'closure_remarks' => $data['remarks'] ?? null,
                ]);
                $workOrder->request->logHistory('closed', 'Work order ' . $workOrder->wo_no . ' verified and closed', 'verification_pending', 'closed');
                NotificationService::notifyUser($workOrder->request->requested_by, 'request_closed',
                    'Request ' . $workOrder->request->request_no . ' closed', 'Maintenance completed and verified.', route('requests.show', $workOrder->request), 'success');
            }

            // Preventive WO -> complete the schedule and move the plan forward
            if ($workOrder->source === 'preventive' && $workOrder->pmSchedule) {
                app(PreventiveMaintenanceService::class)->completeFromWorkOrder($workOrder);
            }
        });
    }

    public function cancel(WorkOrder $workOrder, string $reason): void
    {
        $this->assertStatus($workOrder, ['open', 'assigned', 'on_hold']);
        DB::transaction(function () use ($workOrder, $reason) {
            $from = $workOrder->status;
            $workOrder->update(['status' => 'cancelled', 'final_remarks' => $reason, 'closed_by' => auth()->id(), 'closed_at' => now()]);
            $workOrder->logHistory('cancelled', $reason, $from, 'cancelled');
            if ($workOrder->pmSchedule) {
                $workOrder->pmSchedule->update(['status' => 'skipped']);
            }
        });
    }

    // ------------------------------------------------------------ Helpers

    public function calculateActualCost(WorkOrder $workOrder, float $otherCost = 0): float
    {
        $workOrder->load(['stockTransactions', 'labour']);
        return round($workOrder->partsCost() + $workOrder->labourCost() + $otherCost, 2);
    }

    protected function updateAssetStatus(WorkOrder $workOrder, string $status): void
    {
        $asset = $workOrder->asset;
        if ($asset && $asset->status !== $status && $asset->status !== 'decommissioned') {
            $asset->logHistory('status_changed', 'By work order ' . $workOrder->wo_no, $asset->status, $status);
            $asset->update(['status' => $status]);
        }
    }

    protected function plannedDays(string $priority): int
    {
        return match ($priority) {
            'critical' => 1,
            'high'     => 3,
            'medium'   => 7,
            default    => 14,
        };
    }

    protected function assertStatus(WorkOrder $workOrder, array $allowed): void
    {
        if (!in_array($workOrder->status, $allowed)) {
            throw ValidationException::withMessages([
                'status' => 'This action is not allowed while the work order is "' . status_label($workOrder->status) . '".',
            ]);
        }
    }
}
